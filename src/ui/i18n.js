export function makeT(lang) {
  const base = STRINGS.ru;
  const cur = STRINGS[lang] || base;
  return (key) => {
    const v = cur[key] != null ? cur[key] : base[key];
    if (v == null) return key;
    // вложенные словари (tips, verdictTips) дополняются русскими строками
    if (typeof v === 'object' && !Array.isArray(v) && base[key] && cur !== base) return { ...base[key], ...v };
    return v;
  };
}

export function pickLang(obj, lang) {
  if (!obj) return '';
  return obj[lang] || obj.ru || obj.en || '';
}
